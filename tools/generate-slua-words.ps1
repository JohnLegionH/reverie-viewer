<#
.SYNOPSIS
  Regenerates vendor/slua-words/slua_words.tsv, the words the script editor colours and explains in an SLua (Lua) script.

.DESCRIPTION
  The functions come from the SLua script engine's own function tables, read and never changed: the generated binding files
  LlBindings.g.cs (the ll functions) and OsBindings.g.cs (the ossl, iw and bot functions) of its source folder
  (Source/SLua.ScriptEngine/Bindings in OpenSim-Tranquillity). Each table line names a function, the engine method it calls, what
  it returns and the types of its parameters; that is all the tooltip holds. The Luau reserved words are the language's own and are
  listed here.

  Output: tab-separated lines "kind<TAB>word<TAB>tooltip". kind is "keyword" or "function"; a function's word is qualified by its
  table ("ll.Say"); a tooltip's line breaks are written as \n. Where a function has several signatures each gets a line.

  Run it again, and commit the file, when the engine's tables change:
    pwsh -File tools/generate-slua-words.ps1 -BindingsDir <folder holding LlBindings.g.cs and OsBindings.g.cs>
#>
param(
    [Parameter(Mandatory = $true)][string]$BindingsDir,
    [string]$Out = ''
)

$ErrorActionPreference = 'Stop'
if (-not $Out) { $Out = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) '..\vendor\slua-words\slua_words.tsv' }

# The reserved words of Luau (https://luau.org/syntax): the words a Lua script's own syntax is made of.
$luauKeywords = 'and', 'break', 'continue', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil',
    'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while'

# new BoundFunction("Say", "llSay", FunctionClass.Delayed, "void", new[] { "integer", "string" }, Say ...)   or   new string[0]
$entry = [regex]'new BoundFunction\("(?<name>\w+)", "(?<api>\w+)", FunctionClass\.\w+, "(?<ret>\w+)", (?:new string\[0\]|new\[\] \{(?<params>[^}]*)\})'

function Get-Library([string]$api) {
    if ($api.StartsWith('ll', [StringComparison]::Ordinal)) { return 'll' }
    if ($api.StartsWith('os', [StringComparison]::Ordinal)) { return 'ossl' }
    if ($api.StartsWith('iw', [StringComparison]::Ordinal)) { return 'iw' }
    if ($api.StartsWith('bot', [StringComparison]::Ordinal)) { return 'bot' }
    return $null
}

$signatures = @{}
foreach ($file in 'LlBindings.g.cs', 'OsBindings.g.cs') {
    $path = Join-Path $BindingsDir $file
    if (-not (Test-Path -LiteralPath $path)) { throw "Not found: $path" }
    foreach ($m in $entry.Matches([IO.File]::ReadAllText($path))) {
        $lib = Get-Library $m.Groups['api'].Value
        if ($null -eq $lib) { continue }
        $types = @()
        if ($m.Groups['params'].Success) {
            $types = @([regex]::Matches($m.Groups['params'].Value, '"(\w+)"') | ForEach-Object { $_.Groups[1].Value })
        }
        $word = "$lib." + $m.Groups['name'].Value
        $text = "$word(" + ($types -join ', ') + ')' + $(if ($m.Groups['ret'].Value -ne 'void') { ' -> ' + $m.Groups['ret'].Value } else { '' })
        if (-not $signatures.ContainsKey($word)) { $signatures[$word] = [System.Collections.Generic.List[string]]::new() }
        if (-not $signatures[$word].Contains($text)) { $signatures[$word].Add($text) }
    }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Generated by tools/generate-slua-words.ps1 from the SLua script engine''s function tables. Do not edit by hand.')
$lines.Add('# Copyright (c) 2026 Legion Builds')
$lines.Add('# SPDX-License-Identifier: LGPL-2.1-or-later')
foreach ($k in $luauKeywords | Sort-Object) { $lines.Add("keyword`t$k`t") }
foreach ($word in $signatures.Keys | Sort-Object) { $lines.Add("function`t$word`t" + ($signatures[$word] -join '\n')) }

[IO.File]::WriteAllText($Out, ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
Write-Host ("Wrote {0}: {1} keywords, {2} functions" -f $Out, $luauKeywords.Count, $signatures.Count)
