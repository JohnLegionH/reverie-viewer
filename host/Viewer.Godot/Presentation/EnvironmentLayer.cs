        a1 = 1.0 - a1 * a1; a1 = 1.0 - a1 * a1;
        a1 = clamp(a1 * csun.a, 0.0, 1.0);
        if (a1 > 0.0) {
            float a2 = cn(u2) - 0.5;
            a2 = min(max(a2 + dens, 0.0) * 2.5 * cloud_pd1.z, 1.0);
            a2 = 1.0 - a2; a2 = 1.0 - a2 * a2;
            vec3 col = min(clamp(csun.rgb * (1.0 - a2) + camb, 0.0, 1.0) * 2.0, 1.0);
            vec3 base = vec3(stored1(c.r), stored1(c.g), stored1(c.b));
            vec3 m = mix(base, col, a1);
            c = vec3(min(dec1(m.r) * sky_scale, sky_max), min(dec1(m.g) * sky_scale, sky_max), min(dec1(m.b) * sky_scale, sky_max));
        }
    }
    COLOR = c;
}
