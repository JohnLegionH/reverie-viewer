// e960123230d521e8557a9582100bebcac36a7ca2). CloudLighting.VertexTerms follows the first part of the main() of the cloud shader (since 26.4 in the
// fragment shader, cloudsF.glsl, for each pixel from the dome position that cloudsV.glsl passes on; earlier releases did it in the vertex shader:
