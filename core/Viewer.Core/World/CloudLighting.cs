using System.Numerics;

namespace Viewer.Core.World;

/// <summary>The cloud layer's scroll clock: the pattern moves by the frame's scroll rate over one hundred, per second, accumulated since the viewer started.</summary>
public static class CloudScroll
{
    /// <summary>The scroll after <paramref name="seconds"/> more at <paramref name="rate"/>.</summary>
    public static Vector2 Advance(Vector2 current, Vector2 rate, double seconds) => current + rate * (float)(seconds / 100.0);

    /// <summary>The large texture's offset with the scroll applied: the x scroll is subtracted (the pictures are flipped horizontally), y added.</summary>
    public static Vector2 Offset(Vector3 posDensity1, Vector2 scroll) => new(posDensity1.X - scroll.X, posDensity1.Y + scroll.Y);
}

/// <summary>The terms the cloud vertex shader hands to the fragment shader for one direction.</summary>
public readonly record struct CloudVertexTerms(Vector3 Sun, Vector3 Ambient, float AltitudeBlend, float Density);

/// <summary>A cloud pixel as stored: the colour (0..1) and the opacity it is blended in with.</summary>
public readonly record struct CloudPixel(Vector3 Colour, float Alpha);

/// <summary>The official cloud layer, one view direction at a time.</summary>
public static class CloudLighting
{
    private const double R = SkyLighting.DomeRadius, H = SkyLighting.DomeCameraHeight, Lift = SkyLighting.DomeLift;

    /// <summary>The light the sky and the clouds use: the sun when it is up, else the moon when it is up, else straight down (region axes: x east, y north, z up).</summary>
    public static Vector3 LightOf(SkyFrame f) => f.SunDirection.Z >= 0f ? f.SunDirection : f.MoonDirection.Z >= 0f ? f.MoonDirection : -Vector3.UnitZ;

    /// <summary>The angle (0..180 degrees) between the horizontal parts of a view direction and the light.</summary>
    public static float AzimuthFromLight(SkyFrame f, Vector3 directionEnu)
    {
        var l = LightOf(f);
        double a = Math.Abs(Math.Atan2(directionEnu.Y, directionEnu.X) - Math.Atan2(l.Y, l.X)) * 180.0 / Math.PI % 360.0;
        return (float)(a > 180.0 ? 360.0 - a : a);
    }

    /// <summary>
    /// The cloud vertex shader's terms for the dome vertex in the direction <paramref name="elevationDegrees"/> above the horizon and
    /// <paramref name="azimuthFromLightDegrees"/> from the light's azimuth, worked with the real dome as <see cref="SkyLighting.DomeVertexColour"/> is.
    /// </summary>
    public static CloudVertexTerms VertexTerms(SkyFrame f, float elevationDegrees, float azimuthFromLightDegrees)
    {
        double e = elevationDegrees * Math.PI / 180.0, az = azimuthFromLightDegrees * Math.PI / 180.0;
        double ux = Math.Cos(e) * Math.Cos(az), uy = Math.Sin(e), uz = Math.Cos(e) * Math.Sin(az);
        double b = H * uy, r = -b + Math.Sqrt(b * b - (H * H - R * R));
        double rx = r * ux, ry = r * uy + Lift, rz = r * uz;
        double maxY = f.MaxY;
        double altitude = Math.Clamp((ry + 512.0) / maxY, 0.0, 1.0);
        if (ry > 0) { double k = maxY / ry; rx *= k; ry *= k; rz *= k; }
        else if (ry < 0) { altitude = 0.0; double k = -32000.0 / ry; rx *= k; ry *= k; rz *= k; }
        double len = Math.Sqrt(rx * rx + ry * ry + rz * rz), nx = rx / len, ny = ry / len;

        var ld = LightOf(f);
        bool sunUp = f.SunDirection.Z >= 0f, moonUp = f.MoonDirection.Z >= 0f;
        double lightY = Math.Max(ld.Z, -0.1f), lightX = Math.Sqrt((double)ld.X * ld.X + (double)ld.Y * ld.Y);
        var sunlight = sunUp ? f.SunColor : f.SunColor * 0.7f;
        double[] sun = [sunlight.X, sunlight.Y, sunlight.Z], amb = [f.Ambient.X, f.Ambient.Y, f.Ambient.Z];
        double[] bh = [f.BlueHorizon.X, f.BlueHorizon.Y, f.BlueHorizon.Z], bd = [f.BlueDensity.X, f.BlueDensity.Y, f.BlueDensity.Z];
        double[] cc = [f.Cloud.Color.X, f.Cloud.Color.Y, f.Cloud.Color.Z];
        double hd = f.HazeDensity, hh = f.HazeHorizon, dm = f.DensityMultiplier, cs = f.CloudShadow;

        double factor = sunUp ? 1.0 : moonUp ? f.MoonBrightness * 0.25 : 0.0;
        double glow = Math.Max(1.0 - (nx * lightX + ny * lightY), 0.001) * f.Glow.X;
        glow = Math.Pow(glow, f.Glow.Z) * factor;
        glow = factor < 1.0 ? 0.0 : glow + 0.25;
        double offAxisSky = 1.0 / Math.Max(1e-6, Math.Max(0.0, ny) + lightY), offAxisCloud = 1.0 / Math.Max(1e-6, lightY * 2.0);

        var s = new float[3]; var a = new float[3];
        for (int i = 0; i < 3; i++)
        {
            double atten = (bd[i] + hd * 0.25) * (dm * maxY);
            double combined = Math.Abs(bd[i]) + Math.Abs(hd), bw = bd[i] / combined, hw = hd / combined;
            double trans = Math.Exp(-combined * (len * dm));
            double tmpAmbient = amb[i] + (1.0 - amb[i]) * cs * 0.5;
            double dimmed = sun[i] * Math.Exp(-atten * offAxisSky) * (1.0 - cs);
            double below = bh[i] * bw * (dimmed + tmpAmbient) + hh * hw * (dimmed * glow + tmpAmbient);
            double cloudSun = sun[i] * Math.Exp(-atten * offAxisCloud);
            double t = Math.Sqrt(trans);
            s[i] = (float)(cloudSun * glow * cc[i] * t);
            a[i] = (float)(tmpAmbient * cc[i] * t + below * (1.0 - t));
        }
        return new(new(s[0], s[1], s[2]), new(a[0], a[1], a[2]), (float)altitude, (float)(2.0 * (cs - 0.25)));
    }

    /// <summary>
    /// The dome mesh's planar texture coordinates for a view direction (region axes): the point where the ray from the camera (14400 above the
    /// dome's centre) meets the dome's sphere, east and north over the radius, mapped to 0..1.
    /// </summary>
    public static Vector2 Planar(Vector3 directionEnu)
    {
        double b = H * directionEnu.Z, r = -b + Math.Sqrt(b * b - (H * H - R * R));
        return new((float)((r * directionEnu.X / R + 1.0) / 2.0), (float)((r * directionEnu.Y / R + 1.0) / 2.0));
    }

    /// <summary>The cloud fragment shader's colour and opacity for a view direction, with the scroll applied and the noise sampled from <paramref name="noise"/>.</summary>
    public static CloudPixel Evaluate(SkyFrame f, Vector3 directionEnu, Vector2 scroll, CloudNoise noise)
    {
        var c = f.Cloud;
        if (c.Scale < 0.001f) return default;
        var dir = Vector3.Normalize(directionEnu);
        var v = VertexTerms(f, (float)(Math.Asin(Math.Clamp(dir.Z, -1f, 1f)) * 180.0 / Math.PI), AzimuthFromLight(f, dir));
        var p = Planar(dir);
        var l = LightOf(f);
        // the vertex shader's coordinates: x flipped, centred, divided by the scale; the light's shift (the light in the dome's axes: x is minus north, z is minus east)
        double t0x = (-p.X - 0.5) / c.Scale + 0.5, t0y = (p.Y - 0.5) / c.Scale + 0.5;
        double t1x = t0x + -l.Y * 0.0125, t1y = t0y + -l.X * 0.0125;
        double t2x = t0x * 16, t2y = t0y * 16, t3x = t1x * 16, t3y = t1y * 16;
        double N(double x, double y) => noise.Sample(new Vector2((float)x, (float)y));
        var d1 = CloudScroll.Offset(c.PosDensity1, scroll);
        double k = c.Variance * (1.0 - c.Scale * 0.25);
        double dx = N(t0x / 8, t0y / 8) * k, dy = N((t2x + t0x) / 16, (t2y + t0y) / 16) * k;
        double ex = N((t0x + t2x) / 4, (t0y + t2y) / 4) * k, ey = N((t3x + t1x) / 8, (t3y + t1y) / 8) * k;
        double u1x = t0x + d1.X + dx * 0.2, u1y = t0y + d1.Y + dy * 0.2;
        double u2x = t1x + d1.X, u2y = t1y + d1.Y;
        double u3x = t2x + c.PosDensity2.X, u3y = t2y + c.PosDensity2.Y;
        double variance = Math.Min(1.0, (dx * 2 + dy * 2 + ex + ey) * 4);
        double density = v.Density * (1.0 - variance * variance);
        double a1 = (N(u1x, u1y) - 0.5) + (N(u3x, u3y) - 0.5) * c.PosDensity2.Z;
        a1 = Math.Min(Math.Max(a1 + density, 0.0) * 10 * c.PosDensity1.Z, 1.0);
        a1 = 1.0 - a1 * a1; a1 = 1.0 - a1 * a1;
        a1 = Math.Clamp(a1 * v.AltitudeBlend, 0.0, 1.0);
        double a2 = N(u2x, u2y) - 0.5;
        a2 = Math.Min(Math.Max(a2 + density, 0.0) * 2.5 * c.PosDensity1.Z, 1.0);
        a2 = 1.0 - a2; a2 = 1.0 - a2 * a2;
        float Ch(float sun, float amb) => (float)Math.Min(Math.Clamp(sun * (1.0 - a2) + amb, 0.0, 1.0) * 2.0, 1.0);   // stored in eight bits: at most 1
        return new(new(Ch(v.Sun.X, v.Ambient.X), Ch(v.Sun.Y, v.Ambient.Y), Ch(v.Sun.Z, v.Ambient.Z)), (float)a1);
    }

    /// <summary>
    /// The sky with the cloud over it as the official viewer shows it, as linear light (what the engine takes and encodes): the sky's stored number
    /// (the vertex colour times two, clamped) blended with the cloud's by the opacity in stored values, then made linear, times the classic-lighting
    /// 1.1 and clamped. Where the opacity is zero this is <see cref="SkyLighting.DomeColour"/>.
    /// </summary>
    public static Vector3 ShownOverSky(SkyFrame f, Vector3 directionEnu, Vector2 scroll, CloudNoise noise)
    {
        var dir = Vector3.Normalize(directionEnu);
        var sky = SkyLighting.DomeVertexColour(f, (float)(Math.Asin(Math.Clamp(dir.Z, -1f, 1f)) * 180.0 / Math.PI), AzimuthFromLight(f, dir));
        var cloud = Evaluate(f, dir, scroll, noise);
        float Mix(float s, float c)
        {
            double number = Math.Clamp(s * 2.0, 0.0, 1.0) * (1.0 - cloud.Alpha) + c * (double)cloud.Alpha;
            double lin = number < 0.04045 ? number / 12.92 : Math.Pow((number + 0.055) / 1.055, 2.4);
            return (float)Math.Clamp(lin * 1.1, 0.0, 1.0);
        }
        return new(Mix(sky.X, cloud.Colour.X), Mix(sky.Y, cloud.Colour.Y), Mix(sky.Z, cloud.Colour.Z));
    }
}
