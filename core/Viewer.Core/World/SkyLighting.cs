// Adapted 2026 by Legion Builds. Ported from the Second Life Viewer 26.4 (release tag Second_Life_Release#e960123-26.4, commit
// e960123230d521e8557a9582100bebcac36a7ca2). SkyLighting.Haze follows the main() of the sky shader (since 26.4 the fragment shader, skyF.glsl, works
// this out for each pixel from the dome position that skyV.glsl passes on; earlier releases did it in the vertex shader: the haze and blue weights,
// the sun or moon light attenuated along the ray, the haze distance, the glow, the below-cloud blend) and its colour step (times two, clamped to
// 0..5), translated to C# for one direction at a time, which is the per-pixel result and does not depend on how many vertices the dome has
// (llvowlsky.cpp fixes it at 18 stacks and slices).
// SkyLighting.WhiteFace follows calcAtmosphericVars of atmosphericsFuncs.glsl (the sun's light thinned along its path, the ambient
// raised to 0.9 times 0.57, eased by the face's angle) and the legacy-material branch of softenLightF.glsl in its classic-lighting form (the
// sum taken in the display's encoding, the factors 0.9, 0.7, 1.35 and 1.1), with the settings defaults of the official viewer's settings.xml
// (sky sunlight and ambient scale 1). SurfaceSun is our own fit of the engine's light to that response.
// SkyLighting.Classic, ClassicDiffuse and ClassicSpecular follow the same two shaders for a face's own angle (the ambient eased by the angle, the sun term from the angle to the power
// 1.2 or the shadow, the specular's Fresnel, geometry and normalised lobe of pipeline.cpp createLUTBuffers, here evaluated exactly instead of read from its 1024 by 256 table), translated to C#.
// SkyLighting.DomeVertexColour, DomeShown and DomeColour follow the same sky vertex shader for the real dome: the dome's vertex positions
// (llvowlsky.cpp: a cap of half-angle 22.5 degrees from the pole on a sphere of radius 15000), the camera's place inside it (lldrawpoolwlsky.cpp
// renderDome: camPosLocal = (0, camera height, 0); llenvironment.cpp getCamHeight: dome offset 0.96 times the radius), the 50 m lift of the
// shader's relative position, the real angle between the ray and the clamped light direction (llenvironment.cpp getClampedLightNorm), and the
// display steps after the sky fragment shader (softenLightF.glsl: srgb_to_linear, times 1.1 in classic lighting; postDeferredGammaCorrect.glsl:
// back to the display's encoding), translated to C# for one direction at a time.
// The rest of this file is our own code.
// Copyright (c) 2026 Legion Builds

using System.Numerics;

namespace Viewer.Core.World;

/// <summary>
/// The sky colours and the ambient light a sky frame gives the scene, worked out the way the official viewer's sky shaders do:
/// the frame's blue density and blue horizon are tints weighted by the light (the sun, or the moon at 0.7 when the sun is down,
/// plus the ambient light) and by the haze along the ray to the dome, not colours to paint with. All colours are linear.
/// </summary>
public static class SkyLighting
{
    /// <summary>The elevation (degrees above the horizon) the horizon colour is read at: just above it, where the dome's rays are longest.</summary>
    public const float HorizonElevationDegrees = 2f;

    /// <summary>The sky straight up.</summary>
    /// <summary>The per-metre density of the haze as one number: the official viewer's surviving fraction along a ray is
    /// exp(-(blue_density + haze_density) * length * density_multiplier * distance_multiplier) per colour channel (atmosphericsFuncs.glsl,
    /// calcAtmosphericVars: combined_haze and density_dist); the engine's fog takes one density, the mean of the three channels' exponents.</summary>
    public static float FogDensity(SkyFrame f)
    {
        float mean = (f.BlueDensity.X + f.BlueDensity.Y + f.BlueDensity.Z) / 3f + f.HazeDensity;
        return mean * f.DensityMultiplier * f.DistanceMultiplier;
    }

    public static Vector3 Zenith(SkyFrame f) => Haze(f, 90f);

    /// <summary>The sky just above the horizon.</summary>
    public static Vector3 Horizon(SkyFrame f) => Haze(f, HorizonElevationDegrees);

    /// <summary>
    /// The ambient light the scene receives: the frame's ambient colour at full strength, scaled down only when its largest channel
    /// is above 1 (the official ambient-clamped rule). The scene's ambient energy is 1.
    /// </summary>
    public static Vector3 Ambient(SkyFrame f)
    {
        float m = MathF.Max(f.Ambient.X, MathF.Max(f.Ambient.Y, f.Ambient.Z));
        return m > 1f ? f.Ambient / m : f.Ambient;
    }

    /// <summary>
    /// The colour of the light the moon throws on surfaces: the frame's light colour (the moon shares it with the sun), scaled down so
    /// its largest channel is at most 1. The moon's brightness is not applied here: in the official viewer it only drives the sky's glow
    /// (pipeline.cpp setupHWLights: the moon's diffuse is getMoonlightColor(), clamped; llsettingssky.cpp getMoonlightColor returns the
    /// sunlight colour). Applying it halved the light of a moonlit night.
    /// </summary>
    public static Vector3 MoonLight(SkyFrame f) => LargestChannelAtMostOne(f.SunColor);

    /// <summary>The colour of the sun's light on surfaces: the frame's light colour with its largest channel capped at 1 (pipeline.cpp setupHWLights).</summary>
    public static Vector3 SunLight(SkyFrame f) => LargestChannelAtMostOne(f.SunColor);

    private static Vector3 LargestChannelAtMostOne(Vector3 c)
    {
        float m = MathF.Max(c.X, MathF.Max(c.Y, c.Z));
        return m > 1f ? c / m : c;
    }

    /// <summary>
    /// The linear light a plain white face gets from a frame, at the official viewer's own response for skies without a reflection-probe
    /// ambiance (classic lighting, tone mapping off): the sun's colour thinned by the air along its path (as in the sun-light step of
    /// the atmosphere shader, times 1.35), the ambient colour raised to 0.9 times 0.57 and eased by the face's angle to the light, then
    /// <c>linear(0.9 * ambient + 0.7 * encode(cos^1.2) * sun)</c> times the final scale 1.1. <paramref name="cosine"/> is the dot
    /// product of the face's normal with the light's direction. The value is not clamped.
    /// </summary>
    public static Vector3 WhiteFace(SkyFrame f, float cosine)
    {
        bool sunUp = f.SunDirection.Z >= 0f;
        var light = sunUp ? SunLight(f) : MoonLight(f);
        float lighty = Math.Max(sunUp ? f.SunDirection.Z : f.MoonDirection.Z, -0.1f);   // the official light direction is clamped at -0.1
        var atten = (f.BlueDensity + new Vector3(f.HazeDensity * 0.25f)) * (f.DensityMultiplier * f.MaxY);
        var sunlit = light * Exp(-atten / MathF.Max(1e-6f, lighty)) * 1.35f;
        var tmp = f.Ambient + (Vector3.One - f.Ambient) * (f.CloudShadow * 0.5f);   // more ambient under more cloud
        float ease = 1f - MathF.Pow(MathF.Min(MathF.Abs(cosine), 1f) * 0.5f, 2f);
        var amblit = new Vector3(MathF.Pow(MathF.Max(tmp.X, 0f), 0.9f), MathF.Pow(MathF.Max(tmp.Y, 0f), 0.9f), MathF.Pow(MathF.Max(tmp.Z, 0f), 0.9f)) * (0.57f * ease);
        float sun = Encode(MathF.Pow(Math.Clamp(cosine, 0f, 1f), 1.2f));
        var shown = amblit * 0.9f + sunlit * (0.7f * sun);
        return new Vector3(Decode(shown.X), Decode(shown.Y), Decode(shown.Z)) * 1.1f;
    }

    /// <summary>
    /// The constants of the official classic lighting for one frame (<see cref="Classic"/>), per colour channel: what the shader of a face that takes
    /// the official response needs besides the face's own angles.
    /// </summary>
    /// <param name="Ambient">The ambient term inside the sum, before the face-angle easing: the ambient raised to 0.9 times 0.57, times the sum's 0.9.</param>
    /// <param name="Sun">The sun (or moon) term inside the sum: its colour thinned along its path, times 1.35, times the sum's 0.7.</param>
    /// <param name="SunLinear">The same thinned colour times 1.35 as linear light (the colour a specular highlight is lit with).</param>
    /// <param name="Surface">The light a face turned from the light shows (the ambient alone, no sun, easing 1): <see cref="SurfaceAmbient"/>.</param>
    public readonly record struct ClassicTerms(Vector3 Ambient, Vector3 Sun, Vector3 SunLinear, Vector3 Surface);

    /// <summary>The official classic lighting's constants for a frame.</summary>
    public static ClassicTerms Classic(SkyFrame f)
    {
        bool sunUp = f.SunDirection.Z >= 0f;
        var light = f.SunColor;   // the shader's sunlight and moonlight colours are the sky's light colour as it is (llsettingsvo.cpp applySpecial), not capped at one; the moon shares it
        float lighty = Math.Max(sunUp ? f.SunDirection.Z : f.MoonDirection.Z, -0.1f);   // the official light direction is clamped at -0.1
        var atten = (f.BlueDensity + new Vector3(f.HazeDensity * 0.25f)) * (f.DensityMultiplier * f.MaxY);
        var sunlit = light * Exp(-atten / MathF.Max(1e-6f, lighty)) * 1.35f;
        var tmp = f.Ambient + (Vector3.One - f.Ambient) * (f.CloudShadow * 0.5f);   // more ambient under more cloud
        var amb = new Vector3(MathF.Pow(MathF.Max(tmp.X, 0f), 0.9f), MathF.Pow(MathF.Max(tmp.Y, 0f), 0.9f), MathF.Pow(MathF.Max(tmp.Z, 0f), 0.9f)) * (0.57f * 0.9f);
        return new ClassicTerms(amb, sunlit * 0.7f, new Vector3(Decode(sunlit.X), Decode(sunlit.Y), Decode(sunlit.Z)), SurfaceAmbient(f));
    }

    /// <summary>
    /// The factor the official classic path gives a face's colour (linear, times the final 1.1, not clamped) when its normal has dot product
    /// <paramref name="nl"/> with the light (negative when it faces away): the ambient eased by the angle, the sun term from the angle to the
    /// power 1.2 (not above <paramref name="shadow"/>), both summed in display encoding.
    /// </summary>
    public static Vector3 ClassicDiffuse(SkyFrame f, float nl, float shadow = 1f)
    {
        var t = Classic(f);
        float ease = 1f - MathF.Pow(MathF.Min(MathF.Abs(nl), 1f) * 0.5f, 2f);
        float sun = Encode(MathF.Min(MathF.Pow(Math.Clamp(nl, 0f, 1f), 1.2f), shadow));
        var shown = t.Ambient * ease + t.Sun * sun;
        return new Vector3(Decode(shown.X), Decode(shown.Y), Decode(shown.Z)) * 1.1f;
    }

    /// <summary>
    /// The linear light the official legacy specular adds (times the final 1.1) for a face with the given dot products (normal with light, with the
    /// half vector, with the view; view with the half vector), glossiness and specular colour (linear, already multiplied by its map): the Fresnel
    /// term, the geometry term and the normalised Blinn-Phong lobe (exponent glossiness squared times 368), lit by the sun's thinned colour.
    /// </summary>
    public static Vector3 ClassicSpecular(SkyFrame f, float nl, float nh, float nv, float vh, float glossiness, Vector3 specular, float shadow = 1f)
    {
        if (!(nl > 0f && nh > 0f)) return Vector3.Zero;
        float lit = MathF.Min(nl * 6f, 1f);
        float fres = MathF.Pow(1f - vh, 5f) * 0.4f + 0.5f;
        float gt = MathF.Max(0f, MathF.Min(2f * nh * nv / vh, 2f * nh * nl / vh));
        float n = glossiness * glossiness * 368f;   // pipeline.cpp createLUTBuffers: the exponent is the glossiness squared times RenderSpecularExponent
        float lobe = MathF.Pow(nh, n) * ((n + 2f) * (n + 4f)) / (8f * MathF.PI * (MathF.Pow(2f, -n / 2f) + n));
        float scol = shadow * fres * lobe * gt / (nh * nl);
        return lit * scol * Classic(f).SunLinear * specular * 1.1f;
    }

    /// <summary>The constants of the official lighting of a sky that takes the tone-mapped path (classic_mode 0 in the 26.4 shaders): see <see cref="Eep"/>.</summary>
    /// <param name="Ambient">The ambient before the face-angle easing, per channel: the ambient raised to 0.9 times 0.57 (sRGB-encoded, as the shader keeps it until the sum).</param>
    /// <param name="Sun">The sun (or moon) colour thinned along its path, as linear light.</param>
    public readonly record struct EepTerms(Vector3 Ambient, Vector3 Sun);

    /// <summary>
    /// The constants of the official lighting for a sky with a reflection-probe ambiance (calcAtmosphericVars and calcAtmosphericVarsLinear in atmosphericsFuncs.glsl
    /// with classic_mode 0): the sun's colour thinned along its path and taken to linear light (no factor 1.35), and the ambient before its easing. The ambient the
    /// official viewer takes from a reflection probe's irradiance map instead of the sky (sampleProbeAmbient, mixed by the sky's ambiance) depends on what the probe
    /// captured and is not part of these constants.
    /// </summary>
    public static EepTerms Eep(SkyFrame f)
    {
        bool sunUp = f.SunDirection.Z >= 0f;
        float lighty = Math.Max(sunUp ? f.SunDirection.Z : f.MoonDirection.Z, -0.1f);
        var atten = (f.BlueDensity + new Vector3(f.HazeDensity * 0.25f)) * (f.DensityMultiplier * f.MaxY);
        var sun = f.SunColor * Exp(-atten / MathF.Max(1e-6f, lighty));
        var tmp = f.Ambient + (Vector3.One - f.Ambient) * (f.CloudShadow * 0.5f);
        var amb = new Vector3(MathF.Pow(MathF.Max(tmp.X, 0f), 0.9f), MathF.Pow(MathF.Max(tmp.Y, 0f), 0.9f), MathF.Pow(MathF.Max(tmp.Z, 0f), 0.9f)) * 0.57f;
        return new EepTerms(amb, new Vector3(Decode(sun.X), Decode(sun.Y), Decode(sun.Z)));
    }

    /// <summary>
    /// The factor the official non-classic path gives a face's linear colour when its normal has dot product <paramref name="nl"/> with the light: the ambient eased by
    /// the angle, taken to linear light and reduced to its luminance, plus the sun times the angle (not above <paramref name="shadow"/>). Not clamped.
    /// </summary>
    public static Vector3 EepDiffuse(SkyFrame f, float nl, float shadow = 1f)
    {
        var t = Eep(f);
        float ease = 1f - MathF.Pow(MathF.Min(MathF.Abs(nl), 1f) * 0.5f, 2f);
        var a = t.Ambient * ease;
        float grey = 0.2126f * Decode(a.X) + 0.7152f * Decode(a.Y) + 0.0722f * Decode(a.Z);
        return new Vector3(grey) + t.Sun * MathF.Min(Math.Clamp(nl, 0f, 1f), shadow);
    }

    /// <summary>
    /// <see cref="EepDiffuse(SkyFrame, float, float)"/> with the ambient taken from the sky probe: the grey ambient mixed with <paramref name="probeIrradiance"/> (the irradiance map sampled
    /// in the surface's lookup direction) by the sky's reflection probe ambiance (<see cref="SkyProbe.Ambient"/>), plus the sun times the angle.
    /// </summary>
    public static Vector3 EepDiffuse(SkyFrame f, float nl, Vector3 probeIrradiance, float shadow = 1f)
    {
        var t = Eep(f);
        float ease = 1f - MathF.Pow(MathF.Min(MathF.Abs(nl), 1f) * 0.5f, 2f);
        var a = t.Ambient * ease;
        float grey = 0.2126f * Decode(a.X) + 0.7152f * Decode(a.Y) + 0.0722f * Decode(a.Z);
        return SkyProbe.Ambient(new Vector3(grey), probeIrradiance, f.ProbeAmbiance) + t.Sun * MathF.Min(Math.Clamp(nl, 0f, 1f), shadow);
    }

    /// <summary>The linear light the official non-classic legacy specular adds (the same terms as <see cref="ClassicSpecular"/>, lit by the sun's linear colour, no final factor).</summary>
    public static Vector3 EepSpecular(SkyFrame f, float nl, float nh, float nv, float vh, float glossiness, Vector3 specular, float shadow = 1f)
    {
        if (!(nl > 0f && nh > 0f)) return Vector3.Zero;
        float lit = MathF.Min(nl * 6f, 1f);
        float fres = MathF.Pow(1f - vh, 5f) * 0.4f + 0.5f;
        float gt = MathF.Max(0f, MathF.Min(2f * nh * nv / vh, 2f * nh * nl / vh));
        float n = glossiness * glossiness * 368f;
        float lobe = MathF.Pow(nh, n) * ((n + 2f) * (n + 4f)) / (8f * MathF.PI * (MathF.Pow(2f, -n / 2f) + n));
        float scol = shadow * fres * lobe * gt / (nh * nl);
        return lit * scol * Eep(f).Sun * specular;
    }

    /// <summary>
    /// The ambient light colour (linear, scene ambient energy 1): what a white face turned away from the light shows
    /// (<see cref="WhiteFace"/> at cosine 0).
    /// </summary>
    public static Vector3 SurfaceAmbient(SkyFrame f) => WhiteFace(f, 0f);

    /// <summary>
    /// The sun (or moon) light colour times its energy (linear) for the engine's directional light, whose response is the
    /// cosine of the angle times that colour, on top of <see cref="SurfaceAmbient"/>. The official response is curved (the sun term
    /// is encoded), so each channel's strength is the one that keeps the engine's straight line closest, by the largest gap, to the
    /// official brightness over every angle. Neither side is clamped: the light multiplies the surface colour before the display clips,
    /// so a light factor above 1 brightens every surface that is not white (fitting the clamped curves made the sun about 1.5 times
    /// too strong for grass and rock).
    /// </summary>
    public static Vector3 SurfaceSun(SkyFrame f)
    {
        var a0 = WhiteFace(f, 0f);
        const int steps = 20;
        var curve = new Vector3[steps + 1];
        for (int i = 0; i <= steps; i++) curve[i] = WhiteFace(f, i / (float)steps);
        Span<float> strength = stackalloc float[3];
        for (int c = 0; c < 3; c++)
        {
            float lo = a0[c], top = MathF.Max(curve[steps][c] - lo, 0.01f), best = 0f, bestGap = float.MaxValue;
            for (int s = 0; s <= 400; s++)
            {
                float k = top * 4f * s / 400f, gap = 0f;
                for (int i = 0; i <= steps; i++)
                    gap = MathF.Max(gap, MathF.Abs(lo + k * i / steps - curve[i][c]));
                if (gap < bestGap) { bestGap = gap; best = k; }
            }
            strength[c] = best;
        }
        return new Vector3(strength[0], strength[1], strength[2]);
    }

    /// <summary>The lowest elevation in <see cref="Profile"/> (the sky below it takes this one's colour).</summary>
    public const float ProfileFloorDegrees = 0.5f;

    /// <summary>The number of elevations in <see cref="Profile"/>.</summary>
    public const int ProfileSamples = 96;

    /// <summary>The elevation (degrees above the horizon) of profile sample <paramref name="k"/> of <paramref name="n"/>: dense near the horizon, where the sky changes fastest.</summary>
    public static float ProfileElevation(int k, int n)
    {
        float t = k / (float)(n - 1);
        return ProfileFloorDegrees + (90f - ProfileFloorDegrees) * t * t;
    }

    /// <summary>The sky's shown colour (linear, clamped to 0..1) at each profile elevation, from the horizon to straight up.</summary>
    public static Vector3[] Profile(SkyFrame f, int n = ProfileSamples)
    {
        var p = new Vector3[n];
        for (int k = 0; k < n; k++) p[k] = Vector3.Clamp(Haze(f, ProfileElevation(k, n)), Vector3.Zero, Vector3.One);
        return p;
    }

    /// <summary>The radius of the official sky dome (llsettingssky.cpp DEFAULT_DOME_RADIUS); the camera sits inside it.</summary>
    public const double DomeRadius = 15000.0;
    /// <summary>The camera's height above the dome's centre: the dome offset 0.96 times the radius (llenvironment.cpp getCamHeight), 14400.</summary>
    public const double DomeCameraHeight = 0.96 * DomeRadius;
    /// <summary>The lift the sky vertex shader adds to every vertex's position relative to the camera (skyV.glsl: <c>+ vec3(0, 50, 0)</c>).</summary>
    public const double DomeLift = 50.0;

    /// <summary>The lowest elevation in the dome profile: the official dome's rim (its stacks end 22.5 degrees from the pole, 5.4 degrees below the horizon seen from the camera); below it the sky takes the rim's colour.</summary>
    public const float DomeFloorDegrees = -5f;
    /// <summary>The number of elevations in the dome profile.</summary>
    public const int DomeElevations = 96;
    /// <summary>The number of angles from the light's direction in the dome profile (0 to 180 degrees, dense near the light, where the glow is sharpest).</summary>
    public const int DomeAzimuths = 96;

    /// <summary>The elevation (degrees) of dome profile column <paramref name="k"/> of <paramref name="n"/>: dense near the horizon.</summary>
    public static float DomeElevation(int k, int n)
    {
        float t = k / (float)(n - 1);
        return DomeFloorDegrees + (90f - DomeFloorDegrees) * t * t;
    }

    /// <summary>The angle from the light's azimuth (degrees, 0 to 180) of dome profile row <paramref name="j"/> of <paramref name="m"/>: dense near the light.</summary>
    public static float DomeAzimuth(int j, int m)
    {
        float t = j / (float)(m - 1);
        return 180f * t * t;
    }

    /// <summary>
    /// The sky vertex shader's colour (before the fragment shader's times two) for the dome's vertex that lies in the true direction at
    /// <paramref name="elevationDegrees"/> above the horizon and <paramref name="azimuthFromLightDegrees"/> from the light's azimuth, worked with the
    /// real dome: the ray from the camera (14400 inside a sphere of radius 15000) to the sphere, the shader's +50 lift on that position, the
    /// clamp to the frame's altitude, and the real dot product of that ray with the clamped light direction in the glow term.
    /// </summary>
    public static Vector3 DomeVertexColour(SkyFrame f, float elevationDegrees, float azimuthFromLightDegrees)
    {
        double e = elevationDegrees * Math.PI / 180.0, az = azimuthFromLightDegrees * Math.PI / 180.0;
        // the ray in the shader's space (y up), azimuth measured from the light's azimuth
        double ux = Math.Cos(e) * Math.Cos(az), uy = Math.Sin(e), uz = Math.Cos(e) * Math.Sin(az);
        double b = DomeCameraHeight * uy;
        double r = -b + Math.Sqrt(b * b - (DomeCameraHeight * DomeCameraHeight - DomeRadius * DomeRadius));
        double rx = r * ux, ry = r * uy + DomeLift, rz = r * uz;
        if (ry > 0) { double k = f.MaxY / ry; rx *= k; ry *= k; rz *= k; }
        else if (ry < 0) { double k = -32000.0 / ry; rx *= k; ry *= k; rz *= k; }
        double len = Math.Sqrt(rx * rx + ry * ry + rz * rz);
        double nx = rx / len, ny = ry / len;   // nz is never needed: the light has no component along z

        // the light: the sun when it is up, else the moon when it is up, else straight down; z not below -0.1 and not renormalised
        bool sunUp = f.SunDirection.Z >= 0f, moonUp = f.MoonDirection.Z >= 0f;
        var ld = sunUp ? f.SunDirection : moonUp ? f.MoonDirection : -Vector3.UnitZ;
        double lightY = Math.Max(ld.Z, -0.1f), lightX = Math.Sqrt((double)ld.X * ld.X + (double)ld.Y * ld.Y);
        double dot = nx * lightX + ny * lightY;

        var sunlight = sunUp ? f.SunColor : f.SunColor * 0.7f;
        double[] sun = [sunlight.X, sunlight.Y, sunlight.Z], amb = [f.Ambient.X, f.Ambient.Y, f.Ambient.Z];
        double[] bh = [f.BlueHorizon.X, f.BlueHorizon.Y, f.BlueHorizon.Z], bd = [f.BlueDensity.X, f.BlueDensity.Y, f.BlueDensity.Z];
        double hd = f.HazeDensity, hh = f.HazeHorizon, dm = f.DensityMultiplier, maxY = f.MaxY, cs = f.CloudShadow;
        double glow = Math.Max(1.0 - dot, 0.001) * f.Glow.X;
        glow = Math.Pow(glow, f.Glow.Z);
        double glowFactor = sunUp ? 1.0 : moonUp ? f.MoonBrightness * 0.25 : 0.0;
        glow = glowFactor < 1.0 ? 0.0 : glowFactor * (glow + 0.25);
        double offAxis = 1.0 / Math.Max(1e-6, Math.Max(0.0, ny) + lightY);
        var o = new double[3];
        for (int i = 0; i < 3; i++)
        {
            double atten = (bd[i] + hd * 0.25) * (dm * maxY);
            double combined = Math.Max(Math.Abs(bd[i]) + Math.Abs(hd), 1e-6), bw = bd[i] / combined, hw = hd / combined;
            double sl = sun[i] * Math.Exp(-atten * offAxis);
            double tr = Math.Exp(-combined * (len * dm));
            double c = (bh[i] * bw * (sl + amb[i]) + hh * hw * (sl * glow + amb[i])) * (1.0 - tr);
            double camb = amb[i] + Math.Max(0.0, 1.0 - amb[i]) * cs * 0.5, sl2 = sl * Math.Max(0.0, 1.0 - cs);
            double below = bh[i] * bw * (sl2 + camb) + hh * hw * (sl2 * glow + camb);
            c += (below - c) * (1.0 - Math.Sqrt(Math.Sqrt(tr)));
            o[i] = c;
        }
        return new Vector3((float)o[0], (float)o[1], (float)o[2]);
    }

    /// <summary>
    /// The colour the official viewer shows for the sky in a direction, as a display value (0..1): the vertex colour times two and clamped (skyF.glsl),
    /// stored in an 8-bit buffer (clamped to 1), read as encoded and made linear, times the classic-lighting final scale 1.1, and encoded again by the
    /// gamma pass. The shader's number is shown as it is: it gets no sRGB curve on top.
    /// </summary>
    public static Vector3 DomeShown(SkyFrame f, float elevationDegrees, float azimuthFromLightDegrees)
    {
        var l = DomeColour(f, elevationDegrees, azimuthFromLightDegrees);
        return new Vector3(Encode(l.X), Encode(l.Y), Encode(l.Z));
    }

    /// <summary>The same colour as linear light (<see cref="DomeShown"/> made linear), which is what the engine takes and encodes for the display.</summary>
    public static Vector3 DomeColour(SkyFrame f, float elevationDegrees, float azimuthFromLightDegrees)
    {
        var v = Vector3.Clamp(DomeVertexColour(f, elevationDegrees, azimuthFromLightDegrees) * 2f, Vector3.Zero, new Vector3(1f));
        return Vector3.Clamp(new Vector3(Decode(v.X), Decode(v.Y), Decode(v.Z)) * 1.1f, Vector3.Zero, Vector3.One);
    }

    /// <summary>
    /// The sky's colour in a direction as linear light on the tone-mapped path (a sky that sets a reflection probe ambiance): the same stored sky colour as
    /// <see cref="DomeColour"/> (the vertex colour times two, clamped, made linear), scaled by the sky's high dynamic range scale instead of the classic 1.1
    /// and not clamped again, so it reaches the scale (softenLightF.glsl: the sky's pixels are converted to linear and scaled by the sky's scale).
    /// </summary>
    public static Vector3 DomeColourHdr(SkyFrame f, float elevationDegrees, float azimuthFromLightDegrees, float gamma = 1f)
    {
        var v = Vector3.Clamp(DomeVertexColour(f, elevationDegrees, azimuthFromLightDegrees) * 2f, Vector3.Zero, new Vector3(1f));
        return new Vector3(Decode(v.X), Decode(v.Y), Decode(v.Z)) * ToneMap.HdrScale(gamma);
    }

    /// <summary>The tone-mapped path's dome: <see cref="DomeColourHdr"/> at each elevation and azimuth of <see cref="DomeProfile"/>.</summary>
    public static Vector3[] DomeProfileHdr(SkyFrame f, float gamma = 1f, int n = DomeElevations, int m = DomeAzimuths)
    {
        var p = new Vector3[n * m];
        for (int j = 0; j < m; j++)
            for (int k = 0; k < n; k++) p[j * n + k] = DomeColourHdr(f, DomeElevation(k, n), DomeAzimuth(j, m), gamma);
        return p;
    }

    /// <summary>The dome the renderer draws: <see cref="DomeColour"/> at each <see cref="DomeElevation"/> (columns) and <see cref="DomeAzimuth"/> (rows, row-major).</summary>
    public static Vector3[] DomeProfile(SkyFrame f, int n = DomeElevations, int m = DomeAzimuths)
    {
        var p = new Vector3[n * m];
        for (int j = 0; j < m; j++)
            for (int k = 0; k < n; k++) p[j * n + k] = DomeColour(f, DomeElevation(k, n), DomeAzimuth(j, m));
        return p;
    }

    /// <summary>A linear colour as it is shown: clamped to 0..1 and encoded for the display (sRGB transfer).</summary>
    public static Vector3 ToDisplay(Vector3 linear) => new(Encode(linear.X), Encode(linear.Y), Encode(linear.Z));

    private static float Encode(float v)
    {
        v = Math.Clamp(v, 0f, 1f);
        return v <= 0.0031308f ? v * 12.92f : 1.055f * MathF.Pow(v, 1f / 2.4f) - 0.055f;
    }

    private static float Decode(float v) => v < 0.04045f ? v / 12.92f : MathF.Pow((v + 0.055f) / 1.055f, 2.4f);

    /// <summary>
    /// The sky colour (linear, after the fragment shader's times two and clamp to 5) seen at an elevation above the horizon. The
    /// glow term is read 90 degrees from the light, wherever the sun is: the engine draws the sun's own hot spot, and the dome
    /// colours are the sky around it.
    /// </summary>
    internal static Vector3 Haze(SkyFrame f, float elevationDegrees)
    {
        bool sunUp = f.SunDirection.Z >= 0f, moonUp = f.MoonDirection.Z >= 0f;
        var light = sunUp ? f.SunDirection : moonUp ? f.MoonDirection : -Vector3.UnitZ;
        float lightY = light.Z;   // the shader's y axis is up; ours is z
        var sunlight = sunUp ? f.SunColor : f.SunColor * 0.7f;   // 0.7 matches the legacy moon colour
        float maxY = f.MaxY;

        // the ray to the dome, clamped to its altitude
        float sinE = MathF.Sin(elevationDegrees * (MathF.PI / 180f));
        float rayLength = maxY / sinE;
        float rayY = sinE;

        var blueDensity = f.BlueDensity;
        var lightAtten = (blueDensity + new Vector3(f.HazeDensity * 0.25f)) * (f.DensityMultiplier * maxY);
        var combinedHaze = Vector3.Max(Vector3.Abs(blueDensity) + new Vector3(MathF.Abs(f.HazeDensity)), new Vector3(1e-6f));
        var blueWeight = blueDensity / combinedHaze;
        var hazeWeight = new Vector3(f.HazeDensity) / combinedHaze;

        float offAxis = 1f / MathF.Max(1e-6f, MathF.Max(0f, rayY) + lightY);
        sunlight *= Exp(-lightAtten * offAxis);

        var transparency = Exp(-combinedHaze * (rayLength * f.DensityMultiplier));

        // the haze glow, read at 90 degrees from the light (dot = 0)
        float glow = MathF.Pow(1f * f.Glow.X, f.Glow.Z);
        float glowFactor = sunUp ? 1f : moonUp ? f.MoonBrightness * 0.25f : 0f;
        glow = glowFactor < 1f ? 0f : glowFactor * (glow + 0.25f);

        var ambient = f.Ambient;
        var hazeHorizon = new Vector3(f.HazeHorizon);
        var color = f.BlueHorizon * blueWeight * (sunlight + ambient) + hazeHorizon * hazeWeight * (sunlight * glow + ambient);
        color *= Vector3.One - transparency;

        // more ambient when there are more clouds; the sun dimmed by the cloud shadow
        var cloudAmbient = ambient + Vector3.Max(Vector3.Zero, Vector3.One - ambient) * f.CloudShadow * 0.5f;
        sunlight *= MathF.Max(0f, 1f - f.CloudShadow);
        var belowCloud = f.BlueHorizon * blueWeight * (sunlight + cloudAmbient) + hazeHorizon * hazeWeight * (sunlight * glow + cloudAmbient);

        // less opacity below the clouds; at the horizon the high-altitude colour blends towards the one below them
        var below = Vector3.SquareRoot(transparency);
        color += (belowCloud - color) * (Vector3.One - Vector3.SquareRoot(below));

        return Vector3.Clamp(color * 2f, Vector3.Zero, new Vector3(5f));
    }

    /// <summary>
    /// The tint of the sun's (or the moon's) disc: the light's colour with its brightness taken out (largest channel 1) and mixed towards white, so the disc is
    /// a bright, pale disc that carries the light's hue. The disc does not follow the light's strength: at dusk the sunlight is nearly gone while the disc is still drawn
    /// (the official sun disc comes from the sky's sun texture, not from the light's strength).
    /// </summary>
    public static Vector3 SunDiscTint(SkyFrame f)
    {
        float peak = MathF.Max(f.SunColor.X, MathF.Max(f.SunColor.Y, f.SunColor.Z));
        if (!(peak > 1e-6f)) return Vector3.One;
        const float hueShare = 0.35f;   // how much of the light's hue the disc takes; the rest is white
        return Vector3.Lerp(Vector3.One, f.SunColor / peak, hueShare);
    }

    /// <summary>
    /// The colour a disc leaves in the sky: the sky behind it with the disc's tint added over its coverage (0 outside it, 1 inside), no brighter than the sky's ceiling.
    /// It is never darker than the sky behind it.
    /// </summary>
    public static Vector3 DiscOverSky(Vector3 sky, Vector3 tint, float coverage, float ceiling)
    {
        var lit = Vector3.Min(sky + tint * (coverage * ceiling), new Vector3(ceiling));
        return Vector3.Max(sky, lit);   // a sky already above the ceiling stays as it is
    }

    /// <summary>
    /// What a sky frame gives the haze of the world (the official viewer's atmospherics, class1/windlight/atmosphericsFuncs.glsl calcAtmosphericVars, applied by the haze pass
    /// class3/deferred/hazeF.glsl): <see cref="Constant"/> and <see cref="GlowWeighted"/> make the haze's own light before the distance thins it
    /// (<c>Constant + GlowWeighted * glow</c>, the glow depending on the direction looked), <see cref="Exponent"/> is the per-metre exponent of each channel's
    /// survival (<c>exp(-Exponent * distance)</c>), and the glow shape and the light's direction (z up, as the viewer's frames have it, its height clamped at -0.1 as the official
    /// viewer does) let a shader work the glow out for each pixel.
    /// </summary>
    public readonly record struct HazeTerms(Vector3 Constant, Vector3 GlowWeighted, Vector3 Exponent, Vector3 GlowShape, float GlowFactor, Vector3 LightDirection, Vector3 LightDirectionRaw);

    /// <summary>The haze terms of a frame (the official viewer's calcAtmosphericVars without its per-pixel parts).</summary>
    public static HazeTerms HazeOf(SkyFrame f)
    {
        bool sunUp = f.SunDirection.Z >= 0f, moonUp = f.MoonDirection.Z >= 0f;
        var raw = sunUp ? f.SunDirection : f.MoonDirection;
        var clamped = new Vector3(raw.X, raw.Y, MathF.Max(raw.Z, -0.1f));   // getClampedLightNorm: the light's height is held at -0.1, the vector is not made unit again
        var sunlight = sunUp ? f.SunColor : f.SunColor * 0.7f;   // the moon's light, as the dome uses it
        var blue = f.BlueDensity;
        var hazeDensity = new Vector3(f.HazeDensity);
        // the sunlight dimmed by the air it crosses, by how low the light is (the factor is roughly the cosecant of its height)
        var lightAtten = (blue + hazeDensity * 0.25f) * (f.DensityMultiplier * f.MaxY);
        var combined = Vector3.Max(blue + hazeDensity, new Vector3(1e-6f));
        var blueWeight = blue / combined;
        var hazeWeight = hazeDensity / combined;
        sunlight *= Exp(-lightAtten / MathF.Max(1e-6f, clamped.Z));
        var ambient = f.Ambient;
        var cloudAmbient = ambient + (Vector3.One - ambient) * (f.CloudShadow * 0.5f);   // more ambient when there are more clouds
        var cs = sunlight * (1f - f.CloudShadow);
        var hazeHorizon = new Vector3(f.HazeHorizon);
        return new HazeTerms(
            f.BlueHorizon * blueWeight * (cs + cloudAmbient) + hazeHorizon * hazeWeight * cloudAmbient,
            hazeHorizon * hazeWeight * cs,
            combined * (f.DensityMultiplier * f.DistanceMultiplier),
            f.Glow,
            sunUp ? 1f : moonUp ? f.MoonBrightness * 0.25f : 0f,
            clamped, raw);
    }

    /// <summary>
    /// The haze along a ray of <paramref name="distance"/> metres looking in <paramref name="direction"/> (z up): the survival of each channel and the haze's own light,
    /// as calcAtmosphericVars gives them (the light still in its display encoding, before the haze pass doubles it and makes it linear).
    /// </summary>
    public static (Vector3 Survival, Vector3 Additive) HazeAlong(SkyFrame f, Vector3 direction, float distance)
    {
        var t = HazeOf(f);
        var dir = Vector3.Normalize(direction);
        var survival = Exp(-t.Exponent * distance);
        // the glow: 0 at the light, growing away from it (dampened when not facing it), turned into a bright spot by the shape's negative exponent, plus the least anti-solar light
        float glow = Vector3.Dot(dir, t.LightDirection);
        glow *= MathF.Max(0f, Vector3.Dot(t.LightDirectionRaw, dir));
        glow = MathF.Max(1f - glow, 0.001f) * t.GlowShape.X;
        glow = Math.Clamp(MathF.Pow(glow, t.GlowShape.Z), -100000f, 100000f) + 0.25f;
        glow *= t.GlowFactor;
        var additive = (t.Constant + t.GlowWeighted * glow) * (Vector3.One - survival);
        return (survival, Vector3.Min(additive, new Vector3(10f)));
    }

    /// <summary>
    /// A linear colour seen through the haze, as the haze pass (hazeF.glsl, blended as pipeline.cpp does: source times one plus destination times the source's alpha) leaves it: what is
    /// behind, scaled by the RED channel's survival only, plus the haze's own light (doubled, made linear, times the sky's scale).
    /// </summary>
    public static Vector3 SeenThroughHaze(SkyFrame f, Vector3 sceneLinear, Vector3 direction, float distance, float gamma = 1f)
    {
        var (survival, additive) = HazeAlong(f, direction, distance);
        var light = new Vector3(Decode(additive.X * 2f), Decode(additive.Y * 2f), Decode(additive.Z * 2f)) * ToneMap.HdrScale(gamma);
        return sceneLinear * survival.X + light;
    }

    private static Vector3 Exp(Vector3 v) => new(MathF.Exp(v.X), MathF.Exp(v.Y), MathF.Exp(v.Z));
}
