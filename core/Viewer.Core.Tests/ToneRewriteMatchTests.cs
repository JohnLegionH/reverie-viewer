    private static readonly Dictionary<string, Vector3[][]> Maps = [];
    private static Vector3[][] Map(string frame)
    {
        lock (Maps)
        {
            if (Maps.TryGetValue(frame, out var m)) return m;
            return Maps[frame] = frame switch
            {
                "Midday" => SkyProbe.Irradiance(Midday),
                "Afternoon" => SkyProbe.Irradiance(Afternoon),
                _ => SkyProbe.Irradiance(Afternoon, 1f, SkyProbe.FlatGround(new(0.05f, 0.04f, 0.03f), 64f, 512f)),
            };
        }
    }

    [Theory, MemberData(nameof(Texels))]
    public void An_irradiance_texel_is_what_the_replaced_filtering_gave(string frame, int face, int index)
    {
        var want = IrradianceRows.Single(r => r.Frame == frame && r.Face == face && r.Index == index);
        var got = Map(frame)[face][index];
        // the same samples, frame and order of summation: exact
        Assert.Equal(want.R, got.X); Assert.Equal(want.G, got.Y); Assert.Equal(want.B, got.Z);
    }
